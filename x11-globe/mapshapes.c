/* Convert lat/lon to 3D Cartesian coordinates on sphere surface */
static void latLonToXYZ(float lat, float lon, float radius, float* x, float* y, float* z) {
    double latRad = lat * DEG2RAD;
    double lonRad = -lon * DEG2RAD; /* whoops, longitude on sphere is inverted :-/ */
    *x = (float)(radius * cos(latRad) * cos(lonRad));
    *y = (float)(radius * sin(latRad));
    *z = (float)(radius * cos(latRad) * sin(lonRad));
}
static void drawSegment(const LatLon* points, int numPoints) {
    int i;
    float x, y, z;
    glBegin(GL_LINE_LOOP);
    for (i = 0; i < numPoints; ++i) {
        latLonToXYZ(points[i].lat, points[i].lon, RADIUS * 1.001f, &x, &y, &z);
        glVertex3f(x, y, z);
    }
    glEnd();
}
void drawWireframeMap(void) {
    glColor3f(0.93f, 0.91f, 0.98f);
    drawSegment(africa, sizeof(africa)/sizeof(africa[0]));
    drawSegment(madagaskar, sizeof(madagaskar)/sizeof(madagaskar[0]));
    drawSegment(SouthAmerica, sizeof(SouthAmerica)/sizeof(SouthAmerica[0]));
    drawSegment(NorthAmerica, sizeof(NorthAmerica)/sizeof(NorthAmerica[0]));
    drawSegment(Australia, sizeof(Australia)/sizeof(Australia[0]));
    drawSegment(Greenland, sizeof(Greenland)/sizeof(Greenland[0]));
    drawSegment(UK, sizeof(UK)/sizeof(UK[0]));
    drawSegment(Ireland, sizeof(Ireland)/sizeof(Ireland[0]));
    drawSegment(EurAsia, sizeof(EurAsia)/sizeof(EurAsia[0]));
}
